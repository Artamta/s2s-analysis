def fig_scatter_r2():
    """Forecast vs truth anomaly scatter with R^2, pooled over all
    initializations/weeks/grid cells, for the MME (both seasons, TP+Z500)."""
    fig, axes = plt.subplots(2, 2, figsize=(8.0, 7.6))
    panels = [
        (axes[0, 0], "jfm", "tp", "JFM 2026 — Precipitation (MME)", "mm day$^{-1}$ anomaly"),
        (axes[0, 1], "jfm", "z500", "JFM 2026 — Z500 (MME)", "m anomaly"),
        (axes[1, 0], "jjas", "tp", "JJAS 2019 — Precipitation (MME)", "mm day$^{-1}$ anomaly"),
        (axes[1, 1], "jjas", "z500", "JJAS 2019 — Z500 (MME)", "m anomaly"),
    ]
    for ax, season, var, title, axlabel in panels:
        df = pd.read_csv(GRID[season], usecols=[
            "variable", "model", "forecast_anomaly", "truth_anomaly"])
        sub = df[(df["variable"] == var) & (df["model"] == "mme")].dropna()
        if sub.empty:
            ax.set_visible(False)
            continue
        x, y = sub["truth_anomaly"].values, sub["forecast_anomaly"].values
        r2 = stats.pearsonr(x, y)[0] ** 2
        ax.hexbin(x, y, gridsize=45, cmap="Blues", mincnt=1, bins="log")
        lims = [min(x.min(), y.min()), max(x.max(), y.max())]
        ax.plot(lims, lims, color="#D55E00", lw=1.2, ls="--", label="1:1")
        ax.set_xlim(lims)
        ax.set_ylim(lims)
        ax.set_xlabel(f"ERA5/IMD truth anomaly ({axlabel})")
        ax.set_ylabel(f"Forecast anomaly ({axlabel})")
        ax.set_title(f"{title}\n$R^2={r2:.2f}$, $n={len(x):,}$", fontsize=9.5)
        ax.legend(loc="upper left", fontsize=8, frameon=False)
        ax.set_aspect("equal", adjustable="box")
    fig.tight_layout(h_pad=3.0, w_pad=2.5)
    fig.savefig(f"{OUT}/fig_scatter_r2.pdf")
    plt.close(fig)
    print("wrote fig_scatter_r2.pdf")


def main():
    fig_spatial_acc_maps()
    fig_spatial_acc_z500()
    fig_scatter_r2()
    print(f"\nAll spatial figures written to {OUT}")


if __name__ == "__main__":
    main()
